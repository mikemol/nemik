"""nemik:W598: a card's warrants, W3C PROV-O JSON-LD in its `warrants` list, read into the graph.

The operator's rulings are provenance (2026-10-16: "that's why we call them warrants"). mtools:W1384
writes each as a JSON-LD object on the card (`mikemol-paths-forward --warrant`): the card
prov:wasDerivedFrom a transcript record, which is a prov:Entity generated at a time, attributed
to an agent (urn:nemik:operator for a human record) and generated by an utterance (a prov:Activity).
nemik:WarrantRecordShape (nemik:W599) holds that record to the contract. An entry that does not
parse as JSON-LD, or parses to no statements, is not guessed at: it is returned, and the adapter
marks the card.
"""

import json
import tomllib
from collections.abc import Mapping
from importlib.resources import files

from rdflib import Graph


def ruling_words(text: str | None = None) -> list[str]:
    """Read the phrases that claim an operator ruling (declared in rank-weights.toml [rulings]).

    Args:
        text: The rank-weights TOML, or None for the one that ships with the package.

    Returns:
        The lowercase phrases; empty when the table is absent.

    """
    if text is None:
        text = files("nemik.data").joinpath("rank-weights.toml").read_text()
    document: dict[str, object] = tomllib.loads(text)
    table = document.get("rulings")
    words = table.get("words") if isinstance(table, dict) else None
    return [str(word).lower() for word in words] if isinstance(words, list) else []


WORDS = ruling_words()


def cites_transcript(prose: str) -> bool:
    """Say whether lowercase prose cites an operator utterance by transcript line and uuid.

    Estate writes `operator warrant for W3 verified (host 695f3e0a line 89984, uuid f6a6e6af...)`:
    no claim phrase from the declared list, yet a ruling cited by its record, which belongs in a
    `warrants` list (nemik:W896).

    Args:
        prose: A card's title, evidence and next step, lowercased.

    Returns:
        True when the prose names the operator, a `line` and a `uuid`.

    """
    return "operator" in prose and "line " in prose and "uuid" in prose


def claims_ruling(
    waypoint: Mapping[str, object], words: list[str] | None = None
) -> bool:
    """Say whether an open card claims an operator ruling in prose and carries no warrant.

    Args:
        waypoint: The waypoint as its queue stores it.
        words: The claim phrases, or None for the declared ones.

    Returns:
        True for an open card whose title, evidence or next step uses a claim phrase while its
        `warrants` list is empty.

    """
    if waypoint.get("status") == "done" or waypoint.get("warrants"):
        return False
    prose = " ".join(
        str(waypoint.get(key, "")) for key in ("title", "evidence", "next_bounded_step")
    ).lower()
    if cites_transcript(prose):
        return True
    return any(word in prose for word in (WORDS if words is None else words))


def attach(g: Graph, waypoint: Mapping[str, object]) -> list[str]:
    """Read a waypoint's `warrants` into the graph.

    Args:
        g: The graph being built for the waypoint's queue.
        waypoint: The waypoint as its queue stores it.

    Returns:
        The start of each entry that did not parse as JSON-LD (empty when all did).

    """
    entries = waypoint.get("warrants")
    if not isinstance(entries, list):
        return []
    bad: list[str] = []
    for entry in entries:
        before = len(g)
        try:
            g.parse(data=json.dumps(entry), format="json-ld")
        except (ValueError, TypeError, KeyError):
            bad.append(str(entry)[:80])
            continue
        if len(g) == before:  # parsed, but said nothing: it is not a warrant
            bad.append(str(entry)[:80])
    return bad
